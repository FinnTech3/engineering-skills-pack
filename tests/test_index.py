from __future__ import annotations

from pathlib import Path

from conftest import VALID_SKILL

from skillcheck.index import render_index, usable
from skillcheck.skill import load_skill


def skills_from(root: Path, *names: str):
    return [load_skill(root / n) for n in names]


class TestRenderIndex:
    def test_structure(self, make_skill, root):
        make_skill("alpha-one")
        text = render_index(skills_from(root, "alpha-one"), root.parent)
        assert text.startswith("# Skill index\n")
        assert "<!-- Generated by `skillcheck index`. Do not edit by hand. -->" in text
        assert "1 skill. This file is generated" in text
        assert "| [`alpha-one`](skills/alpha-one/SKILL.md) | Show the smallest skill" in text
        assert "### `alpha-one`" in text
        assert "Use when a demonstration skill is needed to test the validator." in text
        assert text.endswith("\n")
        assert not text.endswith("\n\n")

    def test_plural_count(self, make_skill, root):
        make_skill("alpha-one")
        make_skill("beta-two")
        text = render_index(skills_from(root, "alpha-one", "beta-two"), root.parent)
        assert "2 skills." in text

    def test_sorted_by_name_regardless_of_input_order(self, make_skill, root):
        make_skill("zeta-skill")
        make_skill("alpha-skill")
        text = render_index(skills_from(root, "zeta-skill", "alpha-skill"), root.parent)
        assert text.index("alpha-skill") < text.index("zeta-skill")

    def test_deterministic(self, make_skill, root):
        make_skill("alpha-one")
        skills = skills_from(root, "alpha-one")
        assert render_index(skills, root.parent) == render_index(skills, root.parent)

    def test_links_are_relative_to_the_output_directory(self, make_skill, root):
        make_skill("alpha-one")
        skills = skills_from(root, "alpha-one")
        assert "(skills/alpha-one/SKILL.md)" in render_index(skills, root.parent)
        assert "(alpha-one/SKILL.md)" in render_index(skills, root)
        nested = root.parent / "docs" / "deep"
        nested.mkdir(parents=True)
        assert "(../../skills/alpha-one/SKILL.md)" in render_index(skills, nested)

    def test_pipes_in_purpose_are_escaped(self, make_skill, root):
        text = VALID_SKILL.replace("Show the smallest skill", "Pick a | b")
        make_skill(text=text)
        out = render_index(skills_from(root, "demo-skill"), root.parent)
        assert "| Pick a \\| b that passes every check. |" in out

    def test_description_is_collapsed_to_one_line(self, make_skill, root):
        make_skill()
        out = render_index(skills_from(root, "demo-skill"), root.parent)
        section = out.split("### `demo-skill`\n\n")[1]
        assert "\n" not in section.strip()


class TestUsable:
    def test_complete_skill(self, make_skill):
        assert usable(load_skill(make_skill()))

    def test_missing_purpose(self, make_skill):
        text = VALID_SKILL.replace("## Purpose", "## Aim")
        assert not usable(load_skill(make_skill(text=text)))

    def test_missing_description(self, make_skill):
        assert not usable(load_skill(make_skill(text="---\nname: demo-skill\n---\n# x\n")))

    def test_broken_frontmatter(self, make_skill):
        assert not usable(load_skill(make_skill(text="nope\n")))
